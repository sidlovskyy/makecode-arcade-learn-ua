import { execFile } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { blockCatalog } from './visuals/catalog/index.mjs';
import { validateCatalog, validateSvg } from './visuals/render-blocks-lib.mjs';
import { editorScenes } from './visuals/editor-scenes.mjs';

const exec = promisify(execFile);
export const defaultSiteRoot = fileURLToPath(new URL('../', import.meta.url));

export async function scanVisualAssets(siteRoot, catalog) {
  validateCatalog(catalog);
  // "Committed assets" means these intended checked-in directories, including
  // freshly generated files before commit. Git excludes ignored authoring output.
  const { stdout } = await exec('git', [
    '-C', siteRoot, 'ls-files', '--cached', '--others', '--exclude-standard', '-z',
    '--', 'src/assets/lesson-visuals/blocks/', 'src/assets/lesson-visuals/editor/',
  ]);
  const files = [...new Set(stdout.split('\0').filter(Boolean))].sort();
  const assets = [];
  const ids = new Set();
  for (const file of files) {
    if (!/\.(?:svg|webp)$/.test(file)) continue;
    const match = /^src\/assets\/lesson-visuals\/(blocks|editor)\/([a-z][a-z0-9]*(?:-[a-z0-9]+)*)\.(svg|webp)$/.exec(file);
    if (!match) throw new Error(`${file}: unsupported visual asset path`);
    const [, kind, id, extension] = match;
    const fullPath = path.join(siteRoot, file);
    let stat;
    try {
      stat = await lstat(fullPath);
    } catch (error) {
      // A tracked file can have been intentionally deleted during regeneration.
      // Catalog coverage and registry comparison below catch dangling references.
      if (error.code === 'ENOENT') continue;
      throw new Error(`${id}: cannot read asset: ${error.message}`, { cause: error });
    }
    if (!stat.isFile()) throw new Error(`${id}: asset must be a regular file`);
    if (kind === 'blocks' && extension !== 'svg') throw new Error(`${id}: block asset must be SVG`);
    const assetId = `${kind}:${id}`;
    if (ids.has(assetId)) throw new Error(`${id}: duplicate visual asset ID`);
    if (extension === 'svg') validateSvg(await readFile(fullPath, 'utf8'), id);
    ids.add(assetId);
    assets.push({ id: assetId, kind, file });
  }
  for (const { id } of catalog) {
    if (!ids.has(`blocks:${id}`)) throw new Error(`${id}: missing block SVG`);
  }
  return assets;
}

export async function generateVisualRegistry({ siteRoot = defaultSiteRoot, catalog = blockCatalog, check = false } = {}) {
  const assets = await scanVisualAssets(siteRoot, catalog);
  const imports = assets.map(({ file }, index) => `import asset${index} from '${file.replace('src/', '../')}';`);
  const entries = assets.map(({ id, kind }, index) => {
    const scene = editorScenes.find(scene => scene.id === id);
    const panels = scene?.panels ? scene.panels.length + Number(Boolean(scene.preserveFirstPanel)) : 1;
    return `  '${id}': { kind: '${kind}', src: asset${index}${panels > 1 ? `, panelCount: ${panels}` : ''} },`;
  });
  const source = [
    '// Generated by npm run visuals:registry. Do not edit by hand.',
    ...imports,
    '',
    'export const lessonVisualAssets = {',
    ...entries,
    '} as const;',
    '',
    'export type LessonVisualAssetId = keyof typeof lessonVisualAssets;',
    '',
  ].join('\n');
  const target = path.join(siteRoot, 'src/lesson-visuals/generated-assets.ts');
  if (check) {
    let current;
    try {
      current = await readFile(target, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (current !== source) throw new Error('Visual asset registry is missing or stale; run npm run visuals:registry');
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    const temporary = `${target}.${randomUUID()}.tmp`;
    try {
      await writeFile(temporary, source);
      await rename(temporary, target);
    } finally {
      await rm(temporary, { force: true });
    }
  }
  return assets;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    const assets = await generateVisualRegistry();
    console.log(`Generated registry for ${assets.length} visual asset(s).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
